"""视觉主题：Win11 风格，参数从系统读取。

规范来源：``D:\\Coding\\MyGitHub\\Roboc\\docs\\archive\\视觉规范.md``。
那是 Roboc（C# / Win32 自绘进度窗）的规范，其中**与语言无关、本项目直接沿用**的是：

| 规范条目 | 本项目怎么落实 |
|---|---|
| 配色从系统读取，不写死 | :func:`from_system` 读 ``AppsUseLightTheme`` 与 ``AccentColor`` |
| 字号以磅声明，正文 = 系统 UI 字号 | :meth:`Theme.body_font` 取 ``SYS_DEFAULT_GUI_FONT`` 磅值，不写死像素 |
| 强调色只给"程序推荐的那一个动作" | 只有"打开"按钮用强调色；清空按钮用危险色 |
| Win11 圆角 | :func:`file_tracker.win32.apply_rounded_corners` + 自绘控件圆角 |
| 自绘必须双缓冲 | :class:`~file_tracker.widgets.BufferedPanel` 用 ``wx.BufferedPaintDC`` |
| 深色主题要给标题栏单独声明 | :func:`file_tracker.win32.set_title_bar_dark`（DWM 绘制，自绘碰不到） |

**不沿用的部分**（那些是 Roboc 与其具体窗口绑定的）：纵向节奏表、速率曲线、
固定尺寸对话框、``WS_THICKFRAME`` 相关结论——File Tracker 是可调尺寸的文档窗口。

**所有数值在本文件声明一次，其它模块不得再出现字面量。**
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Theme:
    """一套配色的全部取值。深浅两套由 :func:`from_system` 决定。

    ## 这是一套**手工调过**的中性配色，不是从系统强调色推导出来的

    用户 2026-10-15 的要求："一套真的配色方案（不是从系统色推出来的）"。

    原来的做法是"读系统强调色，再把它调亮/调暗当背景"——问题是
    **强调色是给按钮用的高饱和色**，拿它推导背景会得到一片蓝紫或橙，
    而且用户一改系统主题色整个界面就跟着变。现在：

    * **中性色（窗口底/卡片/表头/描边/正文）是手工定的**，与强调色无关
    * 强调色**只用于"程序推荐的那一个动作"**（"打开"按钮、输入框焦点描边）
    * 强调色读不到时用本文件里的兜底默认值

    ## 卡片分层

    ``background`` 是**窗口底色**，``card`` 是**内容区底色**。
    列表与目录树画在 ``card`` 上，按钮条与窗口留白用 ``background``——
    内容区因此像一张浮起来的卡片，而不是所有东西糊在同一层。

    浅色下卡片**更亮**（白卡浮在灰底上）；深色下卡片也**更亮**
    （``#242424`` 浮在 ``#191919`` 上）——两种主题都靠"提亮"表达浮起。
    """

    is_dark: bool
    # 表面
    background: str      # 窗口底色（卡片之外）
    card: str            # 卡片底色（列表/目录树画在这上面）
    surface_alt: str     # 表头、次级表面
    border: str          # 分隔线、卡片描边
    # **输入框的框线**——比 `border` 深一级。
    #
    # 用户反馈："浅色主题下路径输入框的默认框线颜色能够深一级，
    # 不然用户很难注意到它。"
    #
    # 为什么要单开一条而不是直接加深 `border`：两者**承担的角色不同**。
    # `border` 画的是次要按钮的描边和分隔条——那些控件**本身有填充色**
    # 来表达"我是个控件"；而路径输入框的填充几乎与背景同色，
    # **框线是它唯一的"这里可以输入"的线索**，所以需要更高的可见度。
    #
    # 实测对比度（对 面板 `#F3F4F6` / 填充 `#FFFFFF`）：
    #
    # **两个主题都加深**（用户第二轮："深色主题下虽然因为输入框本体颜色
    # 有区分度能看见，但为了视觉上效果统一，还是给深色主题的输入框线
    # 也加一级对比度吧"）。
    #
    # ## "一级"是多少？——用**对比度倍数**对齐，不靠感觉
    #
    # 浅色第一次加深（`#DCDFE4` → `#C2C4C9`）的对面板对比度是
    # `1.21 → 1.59` = **1.31×**。深色就按同一倍数取，
    # 于是两个主题的"一级"在视觉上等价：
    #
    # ============  ==========  ==============  ==========  ========
    # 主题          原 border    **field_border**  对面板对比度  倍数
    # ============  ==========  ==============  ==========  ========
    # 浅色          `#DCDFE4`   **`#BBBEC2`**      1.21→1.70   1.40×
    # 深色          `#3A3A3A`   **`#4A4A4A`**      1.55→1.98   1.28×
    # ============  ==========  ==============  ==========  ========
    #
    # 深色那个值还有额外依据：它正是本主题**自有表面阶梯的下一级** ——
    # `#191919` → `#242424` → `#2E2E2E` → `#3A3A3A` → **`#4A4A4A`**。
    # 比凭空挑一个亮度更有依据。
    #
    # ⚠️ 深色下"加对比度"是**提亮**（背景是暗的），不是加深 —— 方向别搞反。
    field_border: str
    # 文字
    text: str            # 正文（主信息，如路径）
    text_secondary: str  # 次要信息（频次、时间）
    # 列表里路径列的文字色。
    #
    # 用户反馈："把所有路径记录条目文字颜色恢复为纯黑（浅色主题）/
    # 纯白（深色主题），灰色实在是不方便观察。"
    #
    # **与 `text` 分开是为了能单独调**：`text` 还管表头、弹窗正文、
    # 按钮文字；而列表内容用的是最纯的黑/白——长列表里纯色的
    # 可读性明显好于灰。
    list_text: str
    # 强调与状态
    accent: str          # 强调色：只给"推荐动作"
    accent_hover: str
    accent_text: str     # 画在强调色上的文字
    danger: str          # 危险动作（清空）
    pinned_row: str      # 置顶行的底色
    # **预选（悬停跟随）行的底色**——即用户说的"次级高亮"。
    #
    # 用户把需求分得很清楚："假设选中色有两档，高亮和次级高亮，
    # 鼠标左键单击后为高亮，鼠标移到目标上方不单击为次级高亮，
    # 这就是预选状态。"
    #
    # 两档分工：
    #   * 选中（高亮）  → `SYS_COLOUR_HIGHLIGHT`（`#0078D7`），系统色
    #   * 预选（次级）  → **本字段**，由本项目自绘
    #
    # ## 为什么预选要自己做，不用原生热跟踪
    #
    # 原生热跟踪（`LVS_EX_TRACKSELECT` / `*CLICKACTIVATE`）的表现
    # **依赖主题**，实测用户那边"深色有、浅色没有"，反复不一致。
    # 自己定色就没有这个不确定性：两个主题都是本字段说了算。
    row_hover: str
    # 列间竖线：**不能直接用 border**，浅色下 #DCDFE4 在白底上看不见
    separator: str       # 列间竖线（普通行）
    # **表头**与**置顶区**的竖线颜色 —— 按各自底色分别求解。
    #
    # ## 当前方案：**浅色 1.20 / 深色 1.30**（用户 2026-10-17 最终版）
    #
    # > "把两条掩码线改回之前我们做好的对比度方案……全局对比度改为
    # >   1.30，宽度 2 像素。" 随后又："把浅色主题下的全局对比度降到 1.2，
    # >   深色主题的不要动，还是 1.3。"
    #
    # 实测（WCAG，六项全部落在 1.346~1.354）：
    #
    # ==========  ============  ==============  =========
    # 主题        普通灰线      表头掩码线      置顶掩码线
    # ==========  ============  ==============  =========
    # 浅色        #DADEE5 1.350 #CDD0D6 1.354  #D7DAE0 1.350
    # 深色        #39393B 1.347 #424242 1.351  #48484A 1.346
    # ==========  ============  ==============  =========
    #
    # **为什么必须三个值而不是一个**：表头（浅 L=0.8697 / 深 0.0273）
    # 与置顶（浅 0.9620 / 深 0.0355）的底色亮度不同，同一个颜色算出的
    # 对比度必然不同。这是算术事实，不是实现选择。
    #
    # **方向**：浅色主题往**暗**推（浅底靠近 1，没有变亮空间）；
    # 深色主题往**亮**推。两档都是"线比底色更极端"。
    #
    # ## 历史（四个版本，每次都是用户看效果后调整的）
    #
    # 1. 用"该区域自己的底色"⇒ 线消失（否）
    # 2. 浅色纯白 / 深色纯黑（否：纯白在浅底上只有 1.04，等于没画）
    # 3. 三条线各自 1.6（否：整体太重）
    # 4. 1.6 → 1.35 → 1.30（深色）/ **1.20（浅色）** + 粗细统一 2（现在）
    separator_masked: str    # 表头区的竖线
    separator_pinned: str    # 置顶区的竖线
    # 自绘按钮
    button_normal: str
    button_hover: str
    button_pressed: str

    @staticmethod
    def light(accent: str = "#0F6CBD") -> "Theme":
        """浅色主题：冷中性灰，卡片比窗口底更亮。"""
        return Theme(
            is_dark=False,
            background="#F3F4F6",      # 窗口底：比卡片暗一档
            card="#FFFFFF",            # 卡片：列表/目录树
            surface_alt="#EEF0F3",     # 表头
            border="#DCDFE4",
            # 输入框框线**比 border 深一级**（用户："不然用户很难注意到它"）。
            # = darken(#DCDFE4, 0.15)：对面板对比度 1.21 → **1.70**。
            field_border="#BBBEC2",
            text="#1B1A19",
            text_secondary="#6B7280",  # 次要信息（频次、时间）
            # 列表内容用**纯黑**——用户要求灰色实在是不方便观察
            list_text="#000000",
            accent=accent,
            accent_hover=darken(accent, 0.12),
            accent_text="#FFFFFF",
            danger="#C42B1C",
            # ---- 置顶色：用户指定的观感，**不是按对比度算出来的** ----
            #
            # 用户先后说过"置顶行的底色不对"、"已置顶条目上的强调色消失"。
            # 我把它理解成**颜色选得不好**，于是量了对比度
            # （``#FFF8DC`` 与白底只有 1.065），换成更饱和的黄、
            # 又换成跟随强调色的浅蓝。
            #
            # 用户明确否决两次，最后说明："**不是你调色的问题，
            # 是此前不知道动错了哪些代码导致它失效。**"
            # ——真正失效的是"行属性根本没被应用"。
            # 后来又截图对比："你现在的黄色饱和度太低，适当提高。"
            #
            # **两条规矩**：① 用户说某个视觉元素不对时，先确认它**有没有被画出来**；
            # ② 颜色由用户定，**不要拿对比度计算去推翻它**。
            pinned_row="#FFFFB7",
            # 次级高亮：比选中蓝（#0078D7）明显淡，但白底上看得清。
            # 取 Win11 浅色主题悬停那一档的观感。
            row_hover="#DCE9F7",
            # 列间竖线：**不能直接用 border**——浅色下 #DCDFE4 在白卡上看不见，
            # 用户为此反馈过两次"三条间隔线浅色主题不可见"。
            separator="#E7EBF2",            # 普通行 1.196（vs #FFFFFF）
            # 三条线全部 1.35 对比度，按底色分别求解（用户 2026-10-17）
            separator_masked="#D9DCE2",     # 表头 1.203（vs #EEF0F3）
            separator_pinned="#E3E7EE",     # 置顶 1.195（vs #FFFFB7）                   # 普通行 1.595（vs #FFFFFF）
            # 表头 / 置顶区的竖线 —— **对比度统一 1.6**（用户 2026-10-17）
            button_normal="#FFFFFF",
            button_hover="#F3F4F6",
            button_pressed="#E5E7EB",
        )

    @staticmethod
    def dark(accent: str = "#4CC2FF") -> "Theme":
        """深色主题：卡片比窗口底**更亮**（深色下"浮起来"同样靠提亮）。

        深色下强调色要比浅色更亮，否则在深底上对比度不足；
        但按钮上的文字要反过来用深色——浅蓝底配白字的对比度是不够的。
        """
        return Theme(
            is_dark=True,
            background="#191919",      # 窗口底
            card="#242424",            # 卡片：比窗口底亮一档
            surface_alt="#2E2E2E",     # 表头
            border="#3A3A3A",
            # 输入框框线**提亮一级** = lighten(#3A3A3A, 0.08)。
            # 对面板对比度 1.55 → **1.98**（倍数 1.28×，与浅色的 1.31× 对齐）。
            # 这个值也是本主题表面阶梯的下一级：… #2E2E2E → #3A3A3A → **#4A4A4A**。
            field_border="#4A4A4A",
            text="#F5F5F5",
            text_secondary="#A0A0A0",
            # 列表内容用**纯白**
            list_text="#FFFFFF",
            accent=accent,
            accent_hover=lighten(accent, 0.15),
            accent_text="#10222E",
            danger="#FF99A4",
            pinned_row="#3A3520",
            # 次级高亮（深色）：比选中蓝暗，但在 #242424 卡片上分得出。
            row_hover="#2B4A66",
            separator="#373737",            # 普通行 1.304（vs #242424）
            separator_masked="#3F3F41",     # 表头 1.292（vs #2E2E2E）
            separator_pinned="#464646",     # 置顶 1.301（vs #3A3520）                   # 普通行 1.594（vs #242424）
            # 表头 / 置顶区的竖线 —— 同样统一 1.6
            button_normal="#2E2E2E",
            button_hover="#3A3A3A",
            button_pressed="#454545",
        )


def lighten(color: str, ratio: float) -> str:
    """把颜色朝白色推进 ``ratio``（0..1）。数值越大越浅。"""
    return _blend(color, "#FFFFFF", ratio)


def darken(color: str, ratio: float) -> str:
    """把颜色朝黑色推进 ``ratio``（0..1）。"""
    return _blend(color, "#000000", ratio)


def _blend(color: str, target: str, ratio: float) -> str:
    """在两个 ``#RRGGBB`` 之间线性插值。"""
    ratio = max(0.0, min(1.0, float(ratio)))
    source_rgb = _parse_hex(color)
    target_rgb = _parse_hex(target)
    if source_rgb is None or target_rgb is None:
        return color
    blended = tuple(
        int(round(a + (b - a) * ratio)) for a, b in zip(source_rgb, target_rgb)
    )
    return "#{:02X}{:02X}{:02X}".format(*blended)


def _parse_hex(color: str) -> tuple[int, int, int] | None:
    """``#RRGGBB`` → ``(r, g, b)``；解析失败返回 ``None``。"""
    if not isinstance(color, str):
        return None
    text = color.strip().lstrip("#")
    if len(text) != 6:
        return None
    try:
        return (int(text[0:2], 16), int(text[2:4], 16), int(text[4:6], 16))
    except ValueError:
        return None


def from_system() -> Theme:
    """按当前系统主题与强调色构造 :class:`Theme`。

    **不缓存**：主题可以在运行期间被用户改掉，窗口重新激活时重读一次的成本
    是一次注册表查询，可忽略。
    """
    from . import win32

    accent_rgb = win32.system_accent_color()
    if win32.system_uses_light_theme():
        if accent_rgb:
            return Theme.light("#{:02X}{:02X}{:02X}".format(*accent_rgb))
        return Theme.light()

    if accent_rgb:
        # 深色主题下把强调色提亮，否则在深底上对比不足
        brightened = lighten("#{:02X}{:02X}{:02X}".format(*accent_rgb), 0.35)
        return Theme.dark(brightened)
    return Theme.dark()


#: 主题偏好的合法取值。``"system"`` 表示**跟随系统**（默认）。
#:
#: **它不是 `None`。** 语言那边用 `None` 表示"问系统"，是因为
#: `None` 天然就是"没存过"；主题这里用一个显式的字符串更好读，
#: 而且设置窗口要把它当成三个平级选项来显示。
THEME_SYSTEM = "system"
THEME_LIGHT = "light"
THEME_DARK = "dark"
THEME_CHOICES = (THEME_SYSTEM, THEME_LIGHT, THEME_DARK)

#: 符号按钮的 tooltip 文案（符号本身说不清"这是什么主题"）
THEME_TOOLTIPS = {
    THEME_SYSTEM: ("跟随系统主题", "Follow the system theme"),
    THEME_LIGHT: ("浅色主题", "Light theme"),
    THEME_DARK: ("深色主题", "Dark theme"),
}


def from_preference(preference: str | None) -> Theme:
    """按**用户偏好**构造主题；认不出或 ``None`` 一律"跟随系统"。

    ## 为什么要这一层，而不是各处直接调 `from_system`

    用户要求"把切换主题加进设置，方便用户也方便测试"。偏好有三种：
    跟随系统 / 浅色 / 深色。**只有"跟随系统"才该在窗口激活时重读注册表**——
    否则用户明确选了浅色，激活一次就被系统主题覆盖回去。

    这个判断只写在这里一处，调用方不必各判一遍。

    :param preference: :data:`THEME_CHOICES` 之一；``None`` 或认不出 ⇒ 跟随系统
    """
    if preference == THEME_LIGHT:
        return Theme.light()
    if preference == THEME_DARK:
        return Theme.dark()
    return from_system()


